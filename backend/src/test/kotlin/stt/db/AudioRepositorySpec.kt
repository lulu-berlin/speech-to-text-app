private const val MIB = 1_048_576

class AudioRepositorySpec :
    BehaviorSpec({

        given("an audio stream of two full 1 MiB pages plus 12345 bytes") {
            `when`("it is written for a task and read back to a stream") {
                then(
                    "the source is spooled to disk a page at a time, pages are stored, the bytes come back identical in page windows, size_bytes/sha256 match",
                ) {
                    withDatabase { db ->
                        val size = 2 * MIB + 12_345
                        val taskId = TaskRepository(db).insert(queuedTask("long.wav", createdAt = 1L))
                        val audio = AudioRepository(db)

                        val source = SpoolWatchingSource(GeneratedBytes(size.toLong()), db.tmpDir)
                        audio.write(taskId, source)
                        source.largestUnspooled.shouldBeLessThanOrEqual(MIB.toLong())

                        val expectedSha256 = sha256Hex(GeneratedBytes(size.toLong()))
                        audio.metadata(taskId).shouldBe(AudioMetadata(sizeBytes = 2_109_497L, sha256 = expectedSha256))
                        partLengths(db, taskId).shouldBe(listOf(0 to MIB, 1 to MIB, 2 to 12_345))

                        val target = DigestingOutputStream()
                        audio.copyTo(taskId, target)
                        target.count.shouldBe(2_109_497L)
                        target.sha256Hex().shouldBe(expectedSha256)
                        target.largestWrite.shouldBeLessThanOrEqual(MIB)
                    }
                }
            }
        }

        given("an audio source that delivers one full 1 MiB page and then fails") {
            `when`("it is written for a task") {
                then("the write fails with the source's error and leaves no pages or metadata") {
                    withDatabase { db ->
                        val taskId = TaskRepository(db).insert(queuedTask("broken.wav", createdAt = 1L))

                        shouldThrow<IOException> { AudioRepository(db).write(taskId, FailingAfter(MIB.toLong())) }

                        rowCount(db, "audio_parts").shouldBe(0)
                        rowCount(db, "audio").shouldBe(0)
                    }
                }
            }
        }
    })

/** Deterministic, non-repeating-per-page bytes generated on the fly; never materialized as a whole. */
private class GeneratedBytes(
    private val size: Long,
) : InputStream() {
    private var position = 0L

    private fun byteAt(i: Long): Int = ((i xor (i ushr 8) xor (i ushr 17)) * 131 and 0xFF).toInt()

    override fun read(): Int = if (position >= size) -1 else byteAt(position++)

    override fun read(
        b: ByteArray,
        off: Int,
        len: Int,
    ): Int {
        if (position >= size) return -1
        val n = minOf(len.toLong(), size - position).toInt()
        for (k in 0 until n) b[off + k] = byteAt(position++).toByte()
        return n
    }
}

/**
 * Wraps [source] and records, on every read, how many bytes it has delivered that are not yet
 * in the spool files under [tmpDir]: the bytes the writer holds in memory at that moment.
 */
private class SpoolWatchingSource(
    private val source: InputStream,
    private val tmpDir: Path,
) : InputStream() {
    private var delivered = 0L
    var largestUnspooled = 0L
        private set

    private fun watch() {
        val spooled = Files.list(tmpDir).use { files -> files.mapToLong { Files.size(it) }.sum() }
        largestUnspooled = maxOf(largestUnspooled, delivered - spooled)
    }

    override fun read(): Int = throw UnsupportedOperationException("read in windows")

    override fun read(
        b: ByteArray,
        off: Int,
        len: Int,
    ): Int {
        watch()
        return source.read(b, off, len).also { n -> if (n > 0) delivered += n }
    }
}

/** Delivers [goodBytes] generated bytes, then fails every further read: a source that breaks midway. */
private class FailingAfter(
    goodBytes: Long,
) : InputStream() {
    private val good = GeneratedBytes(goodBytes)

    override fun read(): Int = good.read().also { if (it == -1) throw IOException("audio source broke") }

    override fun read(
        b: ByteArray,
        off: Int,
        len: Int,
    ): Int = good.read(b, off, len).also { if (it == -1) throw IOException("audio source broke") }
}

private class DigestingOutputStream : OutputStream() {
    private val digest = MessageDigest.getInstance("SHA-256")
    var count = 0L
        private set
    var largestWrite = 0
        private set

    override fun write(b: Int) {
        digest.update(b.toByte())
        count++
        largestWrite = maxOf(largestWrite, 1)
    }

    override fun write(
        b: ByteArray,
        off: Int,
        len: Int,
    ) {
        digest.update(b, off, len)
        count += len
        largestWrite = maxOf(largestWrite, len)
    }

    fun sha256Hex(): String = HexFormat.of().formatHex(digest.digest())
}

private fun sha256Hex(input: InputStream): String {
    val digest = MessageDigest.getInstance("SHA-256")
    val buffer = ByteArray(64 * 1024)
    while (true) {
        val n = input.read(buffer)
        if (n < 0) break
        digest.update(buffer, 0, n)
    }
    return HexFormat.of().formatHex(digest.digest())
}

private fun partLengths(
    db: Database,
    taskId: Long,
): List<Pair<Int, Int>> =
    db.connection
        .prepareStatement("SELECT part_no, length(part) FROM audio_parts WHERE task_id = ? ORDER BY part_no")
        .use { st ->
            st.setLong(1, taskId)
            st.executeQuery().use { rs ->
                buildList { while (rs.next()) add(rs.getInt(1) to rs.getInt(2)) }
            }
        }
